#!/usr/bin/env python3
from __future__ import annotations

import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DERIVED = ROOT / "data/derived"
DOCS = ROOT / "docs"
PRE_DIMENSIONAL_PROOF_SUMMARY = DERIVED / "m0_no_dark_statement_pre_dimensional_proof_summary_v13.csv"
STATEMENT_CONTRACT_SUMMARY = DERIVED / "m0_no_dark_frozen_expression_statement_summary_v12.csv"


FIELDNAMES = [
    "freeze_record_id",
    "freeze_record_class",
    "freeze_role",
    "required_evidence",
    "blocked_operation",
    "completion_status",
    "next_required_artifact",
    "forbidden_inputs",
    "freeze_claim_allowed",
    "formula_claim_allowed",
    "numeric_prediction_allowed",
    "endpoint_scoring_allowed",
    "claim_boundary",
]


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle))


def write_csv(path: Path, rows: list[dict[str, object]], fieldnames: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def pre_dimensional_proof_ready() -> bool:
    if not PRE_DIMENSIONAL_PROOF_SUMMARY.exists() or not STATEMENT_CONTRACT_SUMMARY.exists():
        return False
    proof = read_csv(PRE_DIMENSIONAL_PROOF_SUMMARY)
    contract = read_csv(STATEMENT_CONTRACT_SUMMARY)
    return (
        len(proof) == 1
        and proof[0]["overall_status"] == "M0_NO_DARK_STATEMENT_PRE_DIMENSIONAL_PROOF_READY_FOR_FREEZE_PROVENANCE"
        and proof[0]["endpoint_scoring_allowed_anywhere"] == "false"
        and len(contract) == 1
        and contract[0]["overall_status"]
        in {
            "M0_NO_DARK_FROZEN_EXPRESSION_STATEMENT_CONTRACT_READY_FREEZE_PROVENANCE_BLOCKED",
            "M0_NO_DARK_FROZEN_EXPRESSION_STATEMENT_CONTRACT_READY_FOR_PAYLOAD",
        }
        and contract[0]["endpoint_scoring_allowed_anywhere"] == "false"
    )


